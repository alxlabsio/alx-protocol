export type ErrorCodeValue = typeof ErrorCode[keyof typeof ErrorCode];

/** Create an error with a machine-readable code prefix. */
export function protocolError(code: ErrorCodeValue, message: string): Error {
  return new Error(`[${code}] ${message}`);
}
